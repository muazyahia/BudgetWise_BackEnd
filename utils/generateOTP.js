// أداة توليد رمز التحقق OTP - تحتوي على دوال إنشاء رمز التحقق وحساب وقت انتهاء صلاحيته

// دالة توليد رمز تحقق عشوائي مكون من 6 أرقام
// الخطوات:
// 1. توليد رقم عشوائي بين 100000 و 999999
// 2. تحويله إلى نص وإرجاعه
const generateOTP = () => {
  return Math.floor(100000 + Math.random() * 900000).toString();
};

// دالة حساب وقت انتهاء صلاحية رمز التحقق
// الخطوات:
// 1. الحصول على الوقت الحالي بالمللي ثانية
// 2. إضافة 10 دقائق (10 * 60 * 1000 مللي ثانية)
// 3. إنشاء كائن تاريخ جديد بالوقت المحسوب وإرجاعه
const getOTPExpiry = () => {
  return new Date(Date.now() + 10 * 60 * 1000);
};

module.exports = { generateOTP, getOTPExpiry };
